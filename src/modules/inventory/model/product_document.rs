use super::default_version::default_version;
use crate::core::constants::prefixes;
use crate::core::id::generate_id;
use crate::domain::inventory::{BarcodeSource, Product};
use mongodb::bson::DateTime as BsonDateTime;
use mongodb::bson::oid::ObjectId;
use serde::{Deserialize, Serialize};

/// Mongo document shape representing an inventory product.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProductDocument {
    /// MongoDB internal document identifier.
    #[serde(rename = "_id", skip_serializing_if = "Option::is_none")]
    pub id: Option<ObjectId>,
    /// Unique business key identifying this product (e.g. prd_...).
    #[serde(default)]
    pub key: String,
    /// Human-readable SKU code (e.g. PHO-SCR-0001).
    #[serde(default)]
    pub sku: String,
    /// Barcode string for scanning (e.g. EAN-13), if any.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub barcode: Option<String>,
    /// How the barcode was assigned (generated by system or manual).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub barcode_source: Option<BarcodeSource>,
    /// Product name or title.
    #[serde(default)]
    pub name: String,
    /// Foreign key referencing the parent category.
    #[serde(default)]
    pub category_key: String,
    /// Foreign key referencing the subcategory.
    #[serde(default)]
    pub subcategory_key: String,
    /// Current number of units in inventory stock — the sum of the product's
    /// stock movements (a derived column; see `sync::derived_*`).
    #[serde(default)]
    pub stock_quantity: i64,
    /// Minimum threshold count for low-stock warning alerts.
    #[serde(default)]
    pub min_stock_threshold: i64,
    /// True when units of this product are tracked individually by serial number.
    #[serde(default)]
    pub is_serialized: bool,
    /// Warranty length in months, if this product carries one.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub warranty_months: Option<i64>,
    /// Version counter for optimistic locking.
    #[serde(default = "default_version")]
    pub version: i64,
    /// Timestamp when product was created.
    #[serde(default = "BsonDateTime::now")]
    pub created_at: BsonDateTime,
    /// Timestamp when product was last updated.
    #[serde(default = "BsonDateTime::now")]
    pub updated_at: BsonDateTime,
    /// Timestamp when product was soft-deleted, if applicable.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub deleted_at: Option<BsonDateTime>,
    /// Device identifier that last updated this product.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub updated_by_device: Option<String>,
}

impl ProductDocument {
    /// `category_name`/`subcategory_name` are resolved by the service layer
    /// (a lookup by `category_key`/`subcategory_key`) before calling this —
    /// this conversion stays a pure/sync mapping with no DB access, matching
    /// every other `into_*` conversion in this file. `price_tiers` start empty
    /// and are filled from `stock_batches` by
    /// `service::stock_batch::attach_price_tiers`, which every product read
    /// path calls before answering.
    #[must_use]
    pub fn into_product(self, category_name: String, subcategory_name: String) -> Product {
        let key = if self.key.is_empty() {
            generate_id(prefixes::PRODUCT)
        } else {
            self.key
        };
        Product {
            id: self
                .id
                .expect("persisted product document must have an id")
                .to_hex(),
            key,
            sku: self.sku,
            barcode: self.barcode,
            barcode_source: self.barcode_source,
            name: self.name,
            category_key: self.category_key,
            category: category_name,
            subcategory_key: self.subcategory_key,
            subcategory: subcategory_name,
            price_tiers: Vec::new(),
            last_selling_price_cents: None,
            stock_quantity: self.stock_quantity,
            min_stock_threshold: self.min_stock_threshold,
            is_serialized: self.is_serialized,
            warranty_months: self.warranty_months,
            created_at: self.created_at.to_chrono(),
            updated_at: self.updated_at.to_chrono(),
            version: self.version,
            deleted_at: self.deleted_at.map(|d| d.to_chrono()),
            updated_by_device: self.updated_by_device,
        }
    }
}
