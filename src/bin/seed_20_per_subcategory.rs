#[tokio::main]
async fn main() {
    dotenvy::dotenv().ok();
    tracing_subscriber::fmt::init();

    let config = Config::from_env().expect("invalid configuration");
    let db = clients::db::connect_from_config(&config)
        .await
        .expect("failed to connect to database");

    println!("🚀 Reading DB and adding 20 documents for each existing subcategory...");

    let categories_res = category::list_categories(&db)
        .await
        .expect("failed to list categories");

    let mut total_created = 0;
    let mut total_skipped = 0;

    for cat in categories_res.categories {
        println!("\n📂 Category: '{}' (key: {})", cat.name, cat.key);

        for subcat in cat.subcategories {
            println!("  📁 Subcategory: '{}' (key: {})", subcat.name, subcat.key);

            // Fetch existing products in this subcategory to avoid duplicating names
            let existing_products = product::list_products(
                &db,
                ProductListQuery {
                    category_key: Some(cat.key.clone()),
                    subcategory_key: Some(subcat.key.clone()),
                    limit: Some(500),
                    ..Default::default()
                },
            )
            .await
            .expect("failed to list existing products");

            let existing_names: std::collections::HashSet<String> = existing_products
                .items
                .into_iter()
                .map(|p| p.name)
                .collect();

            let templates = get_templates_for_subcategory(&cat.name, &subcat.name);

            let mut created_for_subcat = 0;

            for tmpl in templates {
                if existing_names.contains(tmpl.name) {
                    println!("    ⚠️ Product '{}' already exists, skipping", tmpl.name);
                    total_skipped += 1;
                    continue;
                }

                let req = CreateProductRequest {
                    name: tmpl.name.to_string(),
                    category_key: cat.key.clone(),
                    subcategory_key: subcat.key.clone(),
                    cost_price_cents: tmpl.cost_price_cents,
                    selling_price_cents: tmpl.selling_price_cents,
                    stock_quantity: tmpl.stock_quantity,
                    min_stock_threshold: tmpl.min_stock_threshold,
                    barcode: None,
                    auto_generate_barcode: true,
                    suppliers: Vec::new(),
                    is_serialized: false,
                    warranty_months: None,
                };

                match product::create_product(&db, req).await {
                    Ok(created) => {
                        println!(
                            "    ✅ [{}] {} | SKU: {} | Barcode: {:?} | Stock: {} | Price: ${:.2}",
                            created_for_subcat + 1,
                            created.name,
                            created.sku,
                            created.barcode,
                            created.stock_quantity,
                            created.selling_price_cents as f64 / 100.0
                        );
                        created_for_subcat += 1;
                        total_created += 1;
                    }
                    Err(err) => {
                        eprintln!("    ❌ Error creating product '{}': {:?}", tmpl.name, err);
                    }
                }
            }
            println!(
                "  ✨ Added {} new products to '{}'",
                created_for_subcat, subcat.name
            );
        }
    }

    println!("\n🎉 Finished!");
    println!("   Total new products created: {}", total_created);
    println!("   Total skipped (already existing): {}", total_skipped);
}
